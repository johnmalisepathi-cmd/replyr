// Generates src/lib/worldMap.js: pre-projected SVG paths for the world map
// (Natural Earth projection, Antarctica removed). Run: node scripts/build-world-map.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { geoNaturalEarth1, geoPath } from "d3-geo";
import { merge, mesh } from "topojson-client";
import { presimplify, quantile, simplify } from "topojson-simplify";

const raw = JSON.parse(readFileSync(new URL("../node_modules/world-atlas/countries-50m.json", import.meta.url)));
// Keep coastlines detailed enough to zoom into a city region, light enough for phones.
const pre = presimplify(raw);
const topo = simplify(pre, quantile(pre, Number(process.env.KEEP || 0.2)));
const keep = topo.objects.countries.geometries.filter((g) => g.id !== "010");
const land = merge(topo, keep);
const borders = mesh(topo, { type: "GeometryCollection", geometries: keep }, (a, b) => a !== b);

const W = 1000;
const H = 470;
const projection = geoNaturalEarth1().fitExtent([[4, 4], [W - 4, H - 4]], { type: "Feature", geometry: land });
const path = geoPath(projection).digits(1);

const out = `// Generated by scripts/build-world-map.mjs from world-atlas (Natural Earth, public domain).
export const MAP_W = ${W};
export const MAP_H = ${H};
export const PROJECTION = { scale: ${projection.scale()}, translate: ${JSON.stringify(projection.translate())} };
export const LAND = ${JSON.stringify(path(land))};
export const BORDERS = ${JSON.stringify(path(borders))};
`;
writeFileSync(new URL("../src/lib/worldMap.js", import.meta.url), out);
console.log("bytes", out.length);
